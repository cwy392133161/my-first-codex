"""Optional development tool: build finished audio files, never used by the webpage.

Needs kokoro-onnx==0.4.9, soundfile and ffmpeg; model/voice paths are explicit.
The model stays outside the repository. Run from any working directory.
"""
import argparse
import hashlib
import json
import subprocess
import tempfile
from pathlib import Path

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--model',required=True)
    parser.add_argument('--voices',required=True)
    parser.add_argument('--voice',default='bf_emma')
    parser.add_argument('--limit',type=int,default=0)
    parser.add_argument('--shard-index',type=int,default=0)
    parser.add_argument('--shard-count',type=int,default=1)
    args=parser.parse_args()
    root=Path(__file__).resolve().parent.parent
    data=json.loads(subprocess.check_output(['node',str(root/'scripts/audio-texts.js')]))
    assert args.shard_count>0 and 0<=args.shard_index<args.shard_count
    import numpy as np
    import onnxruntime as ort
    import soundfile as sf
    from kokoro_onnx import Kokoro
    ort.disable_telemetry_events()
    # Avoid hundreds of inference threads on large shared cloud machines.
    original_session=ort.InferenceSession
    def session(*positional,**options):
        settings=ort.SessionOptions()
        settings.intra_op_num_threads=2
        settings.inter_op_num_threads=1
        settings.log_severity_level=3
        options['sess_options']=settings
        return original_session(*positional,**options)
    ort.InferenceSession=session
    voice=Kokoro(args.model,args.voices)
    # This official v1.1 export declares a float speed input. Match that declared
    # interface; the Python frontend otherwise casts new-export speed to int32.
    class ModelInputs:
        def get_inputs(self):return original.get_inputs()
        def run(self,outputs,inputs):
            inputs=dict(inputs)
            if any(i.name=='speed' and i.type=='tensor(float)' for i in original.get_inputs()):
                inputs['speed']=np.array([0.88],dtype=np.float32)
            return original.run(outputs,inputs)
    original=voice.sess
    voice.sess=ModelInputs()
    assert args.voice in voice.voices, f'Voice not found: {args.voice}'
    assets=root/'assets/audio'
    assets.mkdir(parents=True,exist_ok=True)
    mapping={}
    clips=data['clips'][:args.limit] if args.limit else data['clips']
    clips=[clip for index,clip in enumerate(clips) if index%args.shard_count==args.shard_index]
    # Keep temporary output on the asset filesystem so the final rename is atomic.
    with tempfile.TemporaryDirectory(prefix='.build-',dir=assets) as directory:
        wav=Path(directory)/'voice.wav'
        for index,clip in enumerate(clips):
            name=hashlib.sha256(clip['key'].encode()).hexdigest()[:20]+'.mp3'
            destination=assets/name
            if not destination.exists():
                # Expand comparison marks/alternatives for speech, preserve manifest keys.
                text=clip['text'].replace('’',"'").replace('‘',"'").replace(' / ', ', ').replace(' = ', ' means ')
                if "Who's means Who is He's means He is" in text:
                    text="Who's means who is. He's means he is. She's means she is."
                samples,rate=voice.create(text,voice=args.voice,speed=0.88,lang='en-gb')
                assert len(samples)>rate*0.08 and np.max(np.abs(samples))>0.005,clip['key']
                # Small leading/trailing silence prevents short words being clipped.
                samples=np.concatenate([np.zeros(int(rate*.07)),samples,np.zeros(int(rate*.12))])
                sf.write(str(wav),samples,rate,subtype='PCM_16')
                encoded=Path(directory)/'voice.mp3'
                subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-y','-i',str(wav),'-ar','24000','-ac','1','-codec:a','libmp3lame','-b:a','64k','-map_metadata','-1',str(encoded)],check=True)
                encoded.replace(destination)
            mapping[clip['key']]='assets/audio/'+name
            if index%25==0 or index+1==len(clips):print(f'Audio {index+1}/{len(clips)}',flush=True)
    if not args.limit:
        mapping={clip['key']:'assets/audio/'+hashlib.sha256(clip['key'].encode()).hexdigest()[:20]+'.mp3' for clip in data['clips']}
        if not all((root/file).is_file() for file in mapping.values()):
            print(f'Shard {args.shard_index+1}/{args.shard_count} complete; remaining shards still running.',flush=True)
            return
        manifest={'version':1,'voice':{'name':args.voice,'language':'en-GB','source':'Kokoro-82M','kind':'offline-generated'},'clips':mapping}
        source='/* Generated by scripts/build-audio.py; no network service is needed. */\n(function(root){\n  const manifest='+json.dumps(manifest,ensure_ascii=False,separators=(',',':'))+';\n  if(typeof module!=="undefined" && module.exports)module.exports=manifest;\n  else root.GardenAudioManifest=manifest;\n})(typeof window!=="undefined"?window:globalThis);\n'
        (root/'data/audio-manifest.js').write_text(source)
        print(f'Complete: {len(mapping)} clips, {sum(p.stat().st_size for p in assets.glob("*.mp3"))/1024/1024:.2f} MiB',flush=True)

if __name__=='__main__':main()
