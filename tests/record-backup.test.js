'use strict';
const assert = require('node:assert/strict');
const {merge, createBackup, parseBackup} = require('../record-backup.js');
const attempt = (session, correct, review, time) => ({session, topic:'pinyin', question:'pinyin-0', correct, review, time});
const record = a => ({attempts:[a], sessions:[], wrong:a.correct ? [] : ['pinyin-0']});
const old = record(attempt('old', false, false, 1000));
const mastered = record(attempt('mastered', true, true, 1000));
const oldCopy = JSON.stringify(old);
const masteredCopy = JSON.stringify(mastered);
assert.deepEqual(merge(old, mastered).data.wrong, [], '同毫秒的复习答对必须优先于旧错题');
assert.deepEqual(merge(mastered, old).data.wrong, [], '调换合并顺序也不应复活旧错题');
assert.deepEqual(merge(old, record(attempt('normal', true, false, 2000))).data.wrong, ['pinyin-0'], '普通练习答对不移出错题');
const combined = merge(old, mastered).data;
assert.deepEqual(merge(combined, record(attempt('later', false, true, 3000))).data.wrong, ['pinyin-0'], '复习中再次答错，应重新加入错题');
assert.equal(merge(old, old).addedAttempts, 0, '重复恢复不重复统计');
assert.deepEqual(parseBackup(JSON.stringify(createBackup(old))), old, '备份协议可往返');
const conflicting = {attempts:[attempt('old',true,false,1000),attempt('unique',false,false,2000)], sessions:[], wrong:['pinyin-0']};
assert.throws(()=>merge(old, conflicting), /冲突/, '包含新增记录及冲突的文件必须整体拒绝');
assert.equal(JSON.stringify(old), oldCopy, '操作不能修改原输入');
assert.equal(JSON.stringify(mastered), masteredCopy, '操作不能修改导入输入');
assert.throws(()=>parseBackup(JSON.stringify({...createBackup(old), version:2})), /版本/);
assert.throws(()=>parseBackup(JSON.stringify({...createBackup(old), data:{...old, wrong:[]}})), /不一致/);
console.log('通过：备份协议往返、去重、同毫秒双向合并、错题移除与重新加入、普通正确保留错题、冲突原子拒绝及输入保护。');
